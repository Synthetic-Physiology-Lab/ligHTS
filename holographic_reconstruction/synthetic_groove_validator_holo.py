def _load_analyzer_module(target: Path) -> Tuple[Any, str]:
    # Load the holographic analyzer module.

    target = target.resolve()

    if target.is_dir():
        analysis_py = target / "analysis.py"
        if not analysis_py.exists():
            raise RuntimeError(f"{target} does not contain analysis.py")

        sys.modules.pop("analysis", None)
        if str(target) not in sys.path:
            sys.path.insert(0, str(target))
        importlib.invalidate_caches()
        try:
            mod = importlib.import_module("analysis")
        except Exception as e:
            raise RuntimeError(
                f"Failed to import analyzer from folder: {target}\n{e}"
            ) from e
        label = f"refactor:{target.name}"

    elif target.is_file() and target.suffix.lower() == ".py":
        spec = importlib.util.spec_from_file_location(
            "groove_analyzer_holo", str(target)
        )
        if spec is None or spec.loader is None:
            raise RuntimeError(f"Cannot import analyzer: {target}")

        sys.modules.pop(spec.name, None)
        mod = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = mod
        try:
            spec.loader.exec_module(mod)
        except Exception as e:
            raise RuntimeError(f"Failed to import analyzer file: {target}\n{e}") from e
        label = f"monolith:{target.name}"

    else:
        raise RuntimeError(
            "Analyzer path must be a .py file or a folder containing analysis.py"
        )

    if hasattr(mod, "analyze_file"):
        return mod, label
    raise RuntimeError("Analyzer must expose analyze_file function.")


def _analyze_one(
    mod: Any,
    sample: SyntheticSample,
    *,
    outdir: Optional[Path],
) -> Tuple[Dict[str, Any], Optional[str]]:
    # Run the analyzer on one sample

    try:
        kwargs = {
            "outdir": outdir,
        }
        if hasattr(mod, "AnalyzerConfig"):
            try:
                kwargs["config"] = mod.AnalyzerConfig(generate_plots=False)
            except Exception:
                pass

        res_obj = mod.analyze_file(
            Path(sample.file_path),
            xy_um=float(sample.xy_um_per_px),
            dz_um_per_gray=float(sample.dz_um_per_gray),
            z0_um=float(sample.z0_um),
            **kwargs,
        )
    except Exception as e:
        return {}, str(e)

    if isinstance(res_obj, dict):
        res = res_obj
    else:
        try:
            res = asdict(res_obj)
        except Exception:
            res = dict(getattr(res_obj, "__dict__", {}))

    # Extract measured values
    res["pitch_meas_um"] = float(res.get("pitch_um", np.nan))
    res["depth_meas_um"] = float(res.get("depth_um", np.nan))
    res["angle_meas_deg"] = float(res.get("fft_angle_deg", np.nan))
    return res, None


# =============================================================================
# Verification logic
# =============================================================================


def _mape_pct(meas: float, truth: float) -> float:
    # Mean Absolute Percentage Error
    if not (np.isfinite(meas) and np.isfinite(truth) and truth != 0):
        return float("nan")
    return float(abs((meas - truth) / truth) * 100.0)


def _angle_error_deg(meas: float, truth: float) -> float:
    # Angle error accounting for 180° periodicity
    if not np.isfinite(meas) or not np.isfinite(truth):
        return float("nan")
    diff = abs(meas - truth) % 180.0
    return float(min(diff, 180.0 - diff))


def _verify_one(
    mod: Any,
    sample: SyntheticSample,
    cfg: ValidationConfig,
    output_root: Path,
    api_version: str,
) -> VerificationResult:
    # Verify one sample against ground truth

    per_out = output_root / sample.file_name.replace(".tif", "")
    per_out.mkdir(parents=True, exist_ok=True)

    res, err = _analyze_one(mod, sample, outdir=per_out, api_version=api_version)

    # Ground truth angle is always 0 for synthetic holographic data (vertical grooves)
    angle_truth = 0.0

    if err is not None:
        return VerificationResult(
            file_name=sample.file_name,
            sample_index=sample.sample_index,
            passed=False,
            pitch_truth_um=sample.pitch_um,
            depth_truth_um=sample.depth_um,
            angle_truth_deg=angle_truth,
            pitch_meas_um=float("nan"),
            depth_meas_um=float("nan"),
            angle_meas_deg=float("nan"),
            pitch_mape_pct=float("nan"),
            depth_mape_pct=float("nan"),
            pitch_abs_err_um=float("nan"),
            depth_abs_err_um=float("nan"),
            angle_err_deg=float("nan"),
            pitch_pass=False,
            depth_pass=False,
            angle_pass=False,
            error=err,
        )

    pitch_meas = float(res.get("pitch_meas_um", np.nan))
    depth_meas = float(res.get("depth_meas_um", np.nan))
    angle_meas = float(res.get("angle_meas_deg", np.nan))

    pitch_mape = _mape_pct(pitch_meas, sample.pitch_um)
    depth_mape = _mape_pct(depth_meas, sample.depth_um)
    angle_err = _angle_error_deg(angle_meas, angle_truth)

    pitch_abs_err = (
        abs(pitch_meas - sample.pitch_um) if np.isfinite(pitch_meas) else float("nan")
    )
    depth_abs_err = (
        abs(depth_meas - sample.depth_um) if np.isfinite(depth_meas) else float("nan")
    )

    # Tolerances: 2 px for pitch, 2 gray levels for depth
    pitch_abs_tol_um = 2.0 * sample.xy_um_per_px
    depth_abs_tol_um = 2.0 * sample.dz_um_per_gray

    pitch_pass = bool(
        np.isfinite(pitch_meas)
        and (
            (np.isfinite(pitch_mape) and pitch_mape <= cfg.pitch_mape_thresh_pct)
            or (np.isfinite(pitch_abs_err) and pitch_abs_err <= pitch_abs_tol_um)
        )
    )
    depth_pass = bool(
        np.isfinite(depth_meas)
        and (
            (np.isfinite(depth_mape) and depth_mape <= cfg.depth_mape_thresh_pct)
            or (np.isfinite(depth_abs_err) and depth_abs_err <= depth_abs_tol_um)
        )
    )
    angle_pass = bool(np.isfinite(angle_err) and angle_err <= cfg.angle_err_thresh_deg)

    passed = bool(pitch_pass and depth_pass and angle_pass)

    return VerificationResult(
        file_name=sample.file_name,
        sample_index=sample.sample_index,
        passed=passed,
        pitch_truth_um=sample.pitch_um,
        depth_truth_um=sample.depth_um,
        angle_truth_deg=angle_truth,
        pitch_meas_um=pitch_meas,
        depth_meas_um=depth_meas,
        angle_meas_deg=angle_meas,
        pitch_mape_pct=pitch_mape,
        depth_mape_pct=depth_mape,
        pitch_abs_err_um=float(pitch_abs_err),
        depth_abs_err_um=float(depth_abs_err),
        angle_err_deg=float(angle_err),
        pitch_pass=pitch_pass,
        depth_pass=depth_pass,
        angle_pass=angle_pass,
        error="",
    )


