def _setup_logging(level: str) -> None:
    logging.basicConfig(
        level=getattr(logging, level.upper(), logging.INFO),
        format="%(asctime)s [%(levelname)s] %(message)s",
        handlers=[logging.StreamHandler(sys.stdout)],
    )


def main_gui() -> None:
    _setup_logging("INFO")
    _gui_info(
        "Holographic Groove Validation",
        "You will be asked to:\n"
        "1) Select the analyzer (.py)\n"
        "2) Select the dataset folder (must contain truth_index.csv)\n",
    )
    analyzer = _gui_pick_file("Select holographic analyzer (.py)")
    ds = _gui_pick_dir("Select dataset folder (containing truth_index.csv)")
    try:
        run_validation(ds, analyzer)
        _gui_info(
            "Validation Complete", "See VALIDATION_REPORT.md in the dataset folder."
        )
    except Exception as e:
        _gui_info("Validation error", str(e), kind="error")


def main_cli(dataset_dir: str, analyzer_path: str, *, log_level: str) -> None:
    _setup_logging(log_level)
    try:
        run_validation(Path(dataset_dir), Path(analyzer_path))
    except Exception:
        LOG.exception("Validation failed")
        raise SystemExit(1)


