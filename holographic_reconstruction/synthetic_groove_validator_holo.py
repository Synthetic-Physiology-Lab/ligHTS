# Summary and reporting
# =============================================================================


def _stat(values: List[float]) -> Dict[str, float]:
    # Compute mean, std, max of a list of errors
    a = np.asarray(values, dtype=float)
    a = a[np.isfinite(a)]
    if a.size == 0:
        return {"mean": float("nan"), "std": float("nan"), "max": float("nan")}
    return {
        "mean": float(np.mean(a)),
        "std": float(np.std(a, ddof=1)) if a.size > 1 else 0.0,
        "max": float(np.max(a)),
    }


def _summarize(
    results: List[VerificationResult], cfg: ValidationConfig
) -> Dict[str, Any]:
    # Summarize validation results
    total = len(results)
    passed = sum(1 for r in results if r.passed)
    errors = sum(1 for r in results if bool(r.error))
    valid = [r for r in results if not r.error]

    def col(attr: str) -> List[float]:
        return [float(getattr(r, attr)) for r in valid]

    # Group by pitch/depth combination
    combos: Dict[str, Dict[str, Any]] = {}
    for r in results:
        key = f"p{r.pitch_truth_um:.0f}_d{r.depth_truth_um:.0f}"
        if key not in combos:
            combos[key] = {"total": 0, "passed": 0}
        combos[key]["total"] += 1
        if r.passed:
            combos[key]["passed"] += 1

    for key in combos:
        t = combos[key]["total"]
        p = combos[key]["passed"]
        combos[key]["pass_rate"] = (p / t) if t else 0.0

    return {
        "total_samples": total,
        "passed": passed,
        "failed": total - passed,
        "errors": errors,
        "overall_pass_rate": (passed / total) if total else 0.0,
        "pitch_mape": _stat(col("pitch_mape_pct")),
        "depth_mape": _stat(col("depth_mape_pct")),
        "pitch_abs_err_um": _stat(col("pitch_abs_err_um")),
        "depth_abs_err_um": _stat(col("depth_abs_err_um")),
        "angle_err_deg": _stat(col("angle_err_deg")),
        "combo_breakdown": combos,
        "thresholds": asdict(cfg),
    }


def _write_report(
    dataset_dir: Path, summary: Dict[str, Any], results: List[VerificationResult]
) -> Path:
    # Write a markdown validation report
    report = dataset_dir / "VALIDATION_REPORT.md"
    failed = [r for r in results if not r.passed]
    th = summary["thresholds"]

    with open(report, "w", encoding="utf-8") as f:
        f.write("# Holographic Groove Analyzer Validation Report\n\n")
        f.write(f"**Generated:** {summary.get('timestamp', '')}\n\n")
        f.write(f"**Analyzer:** {summary.get('analyzer', '')}\n\n")

        f.write("## Executive Summary\n\n")
        f.write(f"- Total samples: {summary['total_samples']}\n")
        f.write(f"- Passed: {summary['passed']} ({summary['overall_pass_rate']:.1%})\n")
        f.write(f"- Failed: {summary['failed']}\n")
        f.write(f"- Analyzer errors: {summary['errors']}\n\n")

        f.write("## Acceptance Criteria\n\n")
        f.write("| Metric | Threshold |\n|---|---:|\n")
        f.write(f"| Pitch MAPE | ≤ {th['pitch_mape_thresh_pct']}% |\n")
        f.write(f"| Depth MAPE | ≤ {th['depth_mape_thresh_pct']}% |\n")
        f.write(f"| Angle error | ≤ {th['angle_err_thresh_deg']}° |\n\n")

        f.write("## Error Statistics\n\n")
        f.write("| Metric | Mean | Std | Max |\n|---|---:|---:|---:|\n")

        def _fmt_stat(s: Dict[str, float], unit: str = "") -> str:
            return (
                f"{s['mean']:.2f}{unit} | {s['std']:.2f}{unit} | {s['max']:.2f}{unit}"
            )

        f.write(f"| Pitch MAPE | {_fmt_stat(summary['pitch_mape'], '%')} |\n")
        f.write(
            f"| Pitch |abs err| | {_fmt_stat(summary['pitch_abs_err_um'], ' µm')} |\n"
        )
        f.write(f"| Depth MAPE | {_fmt_stat(summary['depth_mape'], '%')} |\n")
        f.write(
            f"| Depth |abs err| | {_fmt_stat(summary['depth_abs_err_um'], ' µm')} |\n"
        )
        f.write(f"| Angle error | {_fmt_stat(summary['angle_err_deg'], '°')} |\n\n")

        f.write("## Results by Pitch/Depth Combination\n\n")
        f.write("| Combination | Total | Passed | Pass Rate |\n|---|---:|---:|---:|\n")
        for key in sorted(summary.get("combo_breakdown", {}).keys()):
            cb = summary["combo_breakdown"][key]
            f.write(
                f"| {key} | {cb['total']} | {cb['passed']} | {cb['pass_rate']:.1%} |\n"
            )
        f.write("\n")

        f.write("## Failed Samples (first 25)\n\n")
        if not failed:
            f.write("No failed samples. ✓\n")
        else:
            f.write("| File | Pitch MAPE | Depth MAPE | Angle err | Reason |\n")
            f.write("|---|---:|---:|---:|---|\n")
            for r in failed[:25]:
                reason = (r.error or "threshold exceeded").replace("\n", " ")[:60]
                f.write(
                    f"| {r.file_name} | {r.pitch_mape_pct:.2f}% | "
                    f"{r.depth_mape_pct:.2f}% | {r.angle_err_deg:.2f}° | {reason} |\n"
                )

    return report


def _log_summary(summary: Dict[str, Any]) -> None:
    # Log a summary of validation results
    LOG.info("=" * 60)
    LOG.info("HOLOGRAPHIC GROOVE VALIDATION SUMMARY")
    LOG.info("=" * 60)
    LOG.info("Analyzer: %s", summary.get("analyzer", ""))
    LOG.info("Total samples: %d", summary.get("total_samples", 0))
    LOG.info(
        "Passed: %d (%.1f%%)",
        summary.get("passed", 0),
        100.0 * float(summary.get("overall_pass_rate", 0.0)),
    )
    LOG.info("Failed: %d", summary.get("failed", 0))
    LOG.info("Errors: %d", summary.get("errors", 0))
    LOG.info("-" * 60)

    def _s(key: str) -> Dict[str, float]:
        s = summary.get(key, {})
        return {
            "mean": float(s.get("mean", float("nan"))),
            "std": float(s.get("std", float("nan"))),
            "max": float(s.get("max", float("nan"))),
        }

    pitch_mape = _s("pitch_mape")
    depth_mape = _s("depth_mape")
    pitch_abs = _s("pitch_abs_err_um")
    depth_abs = _s("depth_abs_err_um")
    angle_err = _s("angle_err_deg")

    LOG.info(
        "Pitch MAPE: %.2f%% ± %.2f%% (max: %.2f%%)",
        pitch_mape["mean"],
        pitch_mape["std"],
        pitch_mape["max"],
    )
    LOG.info(
        "Pitch |abs err|: %.3f ± %.3f µm (max: %.3f µm)",
        pitch_abs["mean"],
        pitch_abs["std"],
        pitch_abs["max"],
    )
    LOG.info(
        "Depth MAPE: %.2f%% ± %.2f%% (max: %.2f%%)",
        depth_mape["mean"],
        depth_mape["std"],
        depth_mape["max"],
    )
    LOG.info(
        "Depth |abs err|: %.3f ± %.3f µm (max: %.3f µm)",
        depth_abs["mean"],
        depth_abs["std"],
        depth_abs["max"],
    )
    LOG.info(
        "Angle error: %.2f° ± %.2f° (max: %.2f°)",
        angle_err["mean"],
        angle_err["std"],
        angle_err["max"],
    )
    LOG.info("-" * 60)

    LOG.info("Per-combination pass rates:")
    cb = summary.get("combo_breakdown", {}) or {}
    for name in sorted(cb.keys()):
        st = cb.get(name, {}) or {}
        total = int(st.get("total", 0))
        passed = int(st.get("passed", 0))
        rate = 100.0 * float(st.get("pass_rate", 0.0)) if total else 0.0
        LOG.info("  %s: %d/%d (%.1f%%)", name, passed, total, rate)

    LOG.info("=" * 60)
    report_path = summary.get("report_path")
    if report_path:
        LOG.info("Validation report written to: %s", report_path)


