# =============================================================================
# Configuration and schema
# =============================================================================


@dataclass(frozen=True)
class ImagingConfig:
    # Imaging parameters matching the holographic synthetic generator
    xy_um: float = 0.54
    dz_um_per_gray: float = 75.0 / 255.0  # ≈ 0.294 µm/gray
    z0_um: float = -25.0


@dataclass(frozen=True)
class ValidationConfig:
    # Acceptance thresholds for holographic groove validation
    pitch_mape_thresh_pct: float = 3.0
    depth_mape_thresh_pct: float = 5.0
    angle_err_thresh_deg: float = 4.0


@dataclass(frozen=True)
class SyntheticSample:
    # Ground truth for a single synthetic sample
    file_name: str
    file_path: Path
    pitch_um: float
    depth_um: float
    xy_um_per_px: float
    dz_um_per_gray: float
    z0_um: float
    sample_index: int


@dataclass
class VerificationResult:
    # Result of validating one sample
    file_name: str
    sample_index: int
    passed: bool

    pitch_truth_um: float
    depth_truth_um: float
    angle_truth_deg: float

    pitch_meas_um: float
    depth_meas_um: float
    angle_meas_deg: float

    pitch_mape_pct: float
    depth_mape_pct: float
    pitch_abs_err_um: float
    depth_abs_err_um: float
    angle_err_deg: float

    pitch_pass: bool
    depth_pass: bool
    angle_pass: bool

    error: str = ""


