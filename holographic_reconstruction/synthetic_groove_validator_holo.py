def _read_truth_index(truth_csv: Path) -> List[SyntheticSample]:
    # Read the truth_index.csv generated by holographic_synthetic_generator.py
    base_dir = truth_csv.parent
    required = {
        "file",
        "pitch_um",
        "depth_um",
        "xy_um_per_px",
        "dz_um_per_gray",
        "z0_um",
    }

    out: List[SyntheticSample] = []
    with open(truth_csv, "r", newline="", encoding="utf-8") as f:
        r = csv.DictReader(f)
        if r.fieldnames is None:
            raise ValueError("truth_index.csv has no header row.")
        missing = required - set(r.fieldnames)
        if missing:
            raise ValueError(f"truth_index.csv missing columns: {sorted(missing)}")

        for row in r:
            file_name = str(row["file"]).strip()
            if not file_name:
                continue

            out.append(
                SyntheticSample(
                    file_name=file_name,
                    file_path=base_dir / file_name,
                    pitch_um=float(row["pitch_um"]),
                    depth_um=float(row["depth_um"]),
                    xy_um_per_px=float(row["xy_um_per_px"]),
                    dz_um_per_gray=float(row["dz_um_per_gray"]),
                    z0_um=float(row["z0_um"]),
                    sample_index=int(row.get("sample_index", 0)),
                )
            )
    return out


def _write_csv(path: Path, rows: List[Dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write("note\nno rows\n")
        return
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


